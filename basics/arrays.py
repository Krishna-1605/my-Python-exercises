### creating an array

cars = ["Ford", "Volvo", "BMW"]

### indexing

cars = ["Ford", "Volvo", "BMW"]
x = cars[0]
print(x)

### modifing

cars = ["Ford", "Volvo", "BMW"]
cars[0] = "Toyota"
print(cars)

### length
cars = ["Ford", "Volvo", "BMW"]
x = len(cars)
print(x)

### looping

cars = ["Ford", "Volvo", "BMW"]
for x in cars:
    print(x)

### append


cars = ["Ford", "Volvo", "BMW"]
cars.append("Honda")
print(cars)

### remove

cars = ["Ford", "Volvo", "BMW"]
cars.remove("BMW")
print(cars)
